#!/usr/bin/env python3
"""
Generates docs/generated/kafka-catalog.md from the RUNNING system (so the documentation can never describe topics or classes that do
not exist): topic metadata comes from the broker (AdminClient via the event-audit-service API), producer/consumer wiring from the
topology the services announced (read from their @EventProducer / @KafkaListener annotations), example payloads from real
messages read back from Kafka (sensitive fields masked by the API).

    python3 scripts/gen_kafka_docs.py          # needs the stack running (scripts/start-all.sh) and some traffic (scripts/e2e.py)
"""
import json, os, urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ENV = dict(l.strip().split("=", 1) for l in open(os.path.join(ROOT, ".env")) if "=" in l and not l.startswith("#"))
GW = "http://localhost:9080"


def call(method, path, body=None, token=None):
    req = urllib.request.Request(GW + path, data=json.dumps(body).encode() if body is not None else None, method=method,
                                 headers={"Content-Type": "application/json", **({"Authorization": "Bearer " + token} if token else {})})
    with urllib.request.urlopen(req, timeout=60) as r:
        return json.loads(r.read().decode() or "null")


token = call("POST", "/api/auth/login", {"usernameOrEmail": "superadmin", "password": ENV["BOOTSTRAP_ADMIN_PASSWORD"]})["accessToken"]
topics = call("GET", "/api/kafka/topics", token=token)
flow = call("GET", "/api/kafka/flow", token=token)
groups = call("GET", "/api/kafka/groups", token=token)
cluster = call("GET", "/api/kafka/cluster", token=token)

edges = flow["edges"]
out = []
w = out.append
w("<!-- GENERATED by scripts/gen_kafka_docs.py from the running system. Do not edit by hand. -->\n")
w(f"**Cluster:** `{cluster['clusterId']}` · brokers: {cluster['brokers']} (KRaft, single node for local development) · "
  f"default partitions 3 · replication factor 1 · retention 7 days (DLT topics 28 days)\n")

w("### Topic catalogue (real broker metadata)\n")
w("| Topic | Purpose | Partitions | RF | Retention | Producer (service / class) | Consumers (service / class) | Consumer groups |")
w("|---|---|---|---|---|---|---|---|")
for t in sorted(topics, key=lambda x: x["name"]):
    if t["deadLetter"]:
        continue
    ret = t["config"].get("retention.ms")
    ret = f"{round(int(ret) / 86400000, 1)} d" if ret else "-"
    prod = "<br>".join(f"`{p}`" for p in t["producers"]) or "-"
    cons = "<br>".join(f"`{c}`" for c in t["consumers"]) or "-"
    grp = "<br>".join(f"`{g}`" for g in t["consumerGroups"]) or "-"
    w(f"| `{t['name']}` | {t['description'] or ''} | {t['partitions']} | {t['replicationFactor']} | {ret} | {prod} | {cons} | {grp} |")

dlts = [t for t in topics if t["deadLetter"]]
w(f"\n**Dead-letter topics ({len(dlts)}):** one `<topic>.DLT` per business topic, 1 partition each, 28-day retention: "
  + ", ".join(f"`{t['name']}`" for t in sorted(dlts, key=lambda x: x['name'])[:4]) + ", ...\n")

w("### Producer → topic → consumer map (from the code of the running services)\n")
w("| Producer service | Producer class | Topic | Consumer service | Consumer class [group] |")
w("|---|---|---|---|---|")
by_topic = {}
for e in edges:
    t = (e["from"] if e["from"].startswith("topic:") else e["to"]).replace("topic:", "")
    by_topic.setdefault(t, {"p": [], "c": []})
    if e["via"] == "produces":
        by_topic[t]["p"].append((e["from"].replace("svc:", ""), e["className"]))
    else:
        by_topic[t]["c"].append((e["to"].replace("svc:", ""), e["className"]))
for t in sorted(by_topic):
    ps, cs = by_topic[t]["p"], by_topic[t]["c"]
    for i in range(max(len(ps), len(cs), 1)):
        p = ps[i] if i < len(ps) else ("", "")
        c = cs[i] if i < len(cs) else ("", "")
        w(f"| {p[0]} | `{p[1]}` | **`{t}`** | {c[0]} | `{c[1]}` |" if p[1] or c[1] else "")

w("\n### Consumer groups (live state)\n")
w("| Group | State | Topics | Members | Total lag |")
w("|---|---|---|---|---|")
for g in sorted(groups, key=lambda x: x["groupId"]):
    w(f"| `{g['groupId']}` | {g['state']} | {len(g['topics'])} | {len(g['members'])} | {g['totalLag']} |")

w("\n### Real event examples (read back from Kafka, sensitive fields masked)\n")
for name in ["order.created", "payment.success", "order.status.updated", "delivery.assigned", "refund.completed"]:
    try:
        msgs = call("GET", f"/api/kafka/topics/{name}/messages?limit=1", token=token)
    except Exception:
        msgs = []
    if not msgs:
        continue
    m = msgs[0]
    w(f"**`{name}`**, key `{m['key']}`, partition {m['partition']}, offset {m['offset']}, headers {json.dumps({k: v for k, v in m['headers'].items() if k in ('eventId', 'eventType', 'X-Correlation-Id')})}\n")
    w("```json\n" + m["value"] + "\n```\n")

os.makedirs(os.path.join(ROOT, "docs", "generated"), exist_ok=True)
path = os.path.join(ROOT, "docs", "generated", "kafka-catalog.md")
open(path, "w").write("\n".join(out) + "\n")
print("wrote", path, f"({len(topics)} topics, {len(edges)} flow edges, {len(groups)} groups)")
