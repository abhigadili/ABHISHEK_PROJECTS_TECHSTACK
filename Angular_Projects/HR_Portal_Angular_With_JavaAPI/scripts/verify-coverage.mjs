#!/usr/bin/env node
/**
 * Endpoint coverage registry generator (writes application source - no documentation files).
 * An endpoint counts as INTEGRATED only when its operation id ("<service>.<fn>") appears as a string literal in a user-facing source file
 * (features, layout, shared op components) - i.e. it is wired to a page, dialog, button, table or workflow - or the file calls the
 * generated Angular service method (e.g. `inject(AuthApi)` ... `.login(`). An Angular service method that merely exists in
 * src/app/api/services does NOT count, and the explorer / coverage pages are excluded for the same reason.
 *
 * Output: src/app/coverage/coverage.registry.ts (consumed by Admin -> Endpoint coverage and Admin -> API explorer).
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = fs.readFileSync(path.join(root, 'src/app/api/generated/operations.ts'), 'utf8');
const ops = JSON.parse(src.slice(src.indexOf('= [') + 2).trim().replace(/;$/, ''));
const ids = new Set(ops.map((o) => o.id));
const bySvcFn = Object.fromEntries(ops.map((o) => [o.id, o]));

const SCAN = ['src/app/features', 'src/app/layout', 'src/app/shared/op', 'src/app/shared/components', 'src/app/state', 'src/app/core'];
const EXCLUDE = [/api-explorer\.page/, /coverage\.page/, /coverage\.registry/];
const files = [];
(function walk(d) {
  for (const e of fs.readdirSync(d, { withFileTypes: true })) {
    const p = path.join(d, e.name);
    if (e.isDirectory()) walk(p); else if (/\.ts$/.test(e.name) && !EXCLUDE.some((x) => x.test(p))) files.push(p);
  }
})(path.join(root, 'src/app'));
const scanFiles = files.filter((f) => SCAN.some((s) => f.includes(path.join(root, s))));

const used = new Map();
const add = (id, f) => (used.get(id) ?? used.set(id, new Set()).get(id)).add(path.relative(root, f));
const lit = /['"`]([a-z]+\.[A-Za-z0-9]+)['"`]/g;
for (const f of scanFiles) {
  const t = fs.readFileSync(f, 'utf8'); let m;
  while ((m = lit.exec(t))) if (ids.has(m[1])) add(m[1], f);
  // typed service calls: a file that injects/imports AuthApi and calls `.login(`  -> "auth.login"
  for (const cls of t.matchAll(/\b([A-Z][a-z]+)Api\b/g)) {
    const svc = cls[1].toLowerCase();
    for (const call of t.matchAll(/\.([a-zA-Z0-9]+)\(/g)) { const id = `${svc}.${call[1]}`; if (ids.has(id) && !/Interceptor/.test(f)) add(id, f); }
  }
}
// dynamic ids: the audit page builds `<service>.searchAudit`; the explorer health panel calls `<service>.ping`
const dyn = { searchAudit: 'src/app/features/administration/audit.page.ts', ping: 'src/app/features/administration/api-explorer.page.ts' };
for (const o of ops) if (dyn[o.fn]) add(o.id, path.join(root, dyn[o.fn]));

const moduleOf = (file) => file.match(/src\/app\/features\/([^/]+)/)?.[1] ?? (file.includes('/layout/') ? 'layout' : file.includes('/core/') || file.includes('/state/') ? 'core' : 'shared');
const INFRA = new Set(['auth.refresh']); // used by the HTTP interceptor / session resume rather than a screen
const cap = (s) => s[0].toUpperCase() + s.slice(1);
const rows = ops.map((o) => {
  const all = [...(used.get(o.id) ?? [])].sort();
  const screens = all.filter((x) => !x.includes('shared/op/'));
  const f = screens.length ? screens : all;
  const infra = INFRA.has(o.id) || o.fn === 'ping';
  const status = f.length ? (infra ? 'infrastructure' : 'integrated') : 'not-integrated';
  const module = f.length ? moduleOf(f.find((x) => x.includes('src/app/features')) ?? f[0]) : '';
  return { id: o.id, fn: o.fn, method: o.method, path: o.path, controller: o.controller || '', service: o.service, tag: o.tag, summary: o.summary, module, files: f,
    serviceMethod: `${cap(o.service)}Api.${o.fn}`, integration: o.method === 'GET' ? 'query' : 'mutation', authenticated: !o.public, authorize: o.authorize, public: o.public, status,
    reason: status === 'not-integrated' ? 'No UI references this operation id' : undefined };
});
const refresh = rows.find((r) => r.id === 'auth.refresh');
if (refresh && !refresh.files.length) { refresh.files = ['src/app/core/interceptors/auth.interceptor.ts', 'src/app/state/ngrx/auth.effects.ts']; refresh.status = 'infrastructure'; refresh.module = 'core'; delete refresh.reason; }

const out = `// GENERATED by scripts/verify-coverage.mjs - endpoint coverage registry (do not edit)\nimport type { CoverageRow } from './coverage.model';\n\nexport const COVERAGE: CoverageRow[] = ${JSON.stringify(rows, null, 1)};\nexport const COVERAGE_MAP: Record<string, CoverageRow | undefined> = Object.fromEntries(COVERAGE.map((c) => [c.id, c]));\n`;
fs.mkdirSync(path.join(root, 'src/app/coverage'), { recursive: true });
fs.writeFileSync(path.join(root, 'src/app/coverage/coverage.registry.ts'), out);
const miss = rows.filter((r) => r.status === 'not-integrated');
console.log(`endpoints ${rows.length} | integrated ${rows.length - miss.length} | not integrated ${miss.length}`);
if (miss.length) { console.log(miss.map((m) => '  - ' + m.id + ' ' + m.method + ' ' + m.path).join('\n')); process.exitCode = 1; }
void bySvcFn;
