/// <summary>BackgroundService: daily expiry reminders (interval from configuration).</summary>
public sealed class ExpiryReminderJob(IServiceScopeFactory scopes, IConfiguration cfg, ILogger<ExpiryReminderJob> log)
    : PeriodicJob(scopes, cfg, log, "document-expiry", "Scheduler:ExpiryReminderIntervalSeconds", 86400)
{
    protected override async Task RunAsync(IServiceProvider services, CancellationToken ct)
    {
        var n = await services.GetRequiredService<IDocumentService>().RemindExpiringAsync(ct);
        if (n > 0) log.LogInformation("Published {Count} document expiry reminders", n);
    }
}

/// <summary>Seeds the categories other services depend on (idempotent and additive: existing categories are never touched).</summary>
public sealed class CategorySeeder(IServiceScopeFactory scopes, ILogger<CategorySeeder> log) : IHostedService
{
    private static readonly (string Code, string Name, string Roles, bool SelfUpload)[] Needed =
    [
        ("PAYSLIP", "Payslip", "PAYROLL_ADMIN,FINANCE_ADMIN,SUPER_ADMIN", false), ("TAX", "Tax document", "FINANCE_ADMIN,HR_ADMIN,SUPER_ADMIN", false),
        ("EXIT", "Exit document", "HR_ADMIN,SUPER_ADMIN", false), ("LEAVE_ATTACHMENT", "Leave attachment", "HR_ADMIN,SUPER_ADMIN", true)
    ];

    public async Task StartAsync(CancellationToken ct)
    {
        for (var attempt = 1; attempt <= 5; attempt++)
        {
            try
            {
                using var scope = scopes.CreateScope();
                var db = scope.ServiceProvider.GetRequiredService<DocumentDbContext>();
                foreach (var (code, name, roles, self) in Needed)
                    if (!await db.DocumentCategories.IgnoreQueryFilters().AnyAsync(c => c.Code == code, ct))
                        db.DocumentCategories.Add(new DocumentCategory { Code = code, Name = name, ReadRoles = roles, RequiresVerification = false, SelfUploadAllowed = self, IsSensitive = false, Active = true });
                await db.SaveChangesAsync(ct);
                return;
            }
            catch (Exception ex) when (attempt < 5 && !ct.IsCancellationRequested) { log.LogWarning("Category seed attempt {Attempt} failed: {Error}", attempt, ex.Message); await Task.Delay(2000, ct); }
        }
    }

    public Task StopAsync(CancellationToken ct) => Task.CompletedTask;
}

/// <summary>Payslip PDFs generated by Payroll are registered here so employees find them in their document list (idempotent consumer).</summary>
public sealed class PayslipGeneratedHandler(IDocumentService documents) : EventHandlerBase<PayslipGeneratedEvent>
{
    public override string Topic => Topics.PayslipGenerated;
    protected override Task HandleAsync(PayslipGeneratedEvent e, CancellationToken ct) =>
        documents.RegisterSystemDocumentAsync(e.EmployeeId, "PAYSLIP", $"Payslip {e.Year}-{e.Month:D2}", e.FileName, e.FilePath, "", e.SizeBytes, "PAYSLIP", ct);
}
