#!/usr/bin/env python3
"""Generates request/response DTOs for reference-data entities from the scaffolded entity classes + information_schema.
usage: generate-dtos.py <ServiceName> <outfile> Entity:table[:DtoBase[:ExcludeCsv]] ...   (reads .env for MySQL access)"""
import os, re, subprocess, sys

def env():
    d = {}
    for l in open('.env'):
        if '=' in l and not l.startswith('#'):
            k, v = l.rstrip('\n').split('=', 1); d[k] = v.strip("'\"")
    return d

E = env()
svc, out, *specs = sys.argv[1:]
db = dict(l.split('\t') for l in open('scripts/services.tsv').read().strip().split('\n') if False) if False else None
rows = [l.split('\t') for l in open('scripts/services.tsv').read().strip().split('\n')]
database = next(r[1] for r in rows if r[0] == svc)

def q(sql):
    r = subprocess.run(['mysql', f"-h{E['MYSQL_HOST']}", f"-P{E['MYSQL_PORT']}", f"-u{E['MYSQL_USER']}", f"-p{E['MYSQL_PASSWORD']}", '-N', '-B', '-e', sql],
                       capture_output=True, text=True)
    return [l.split('\t') for l in r.stdout.strip().split('\n') if l]

SYS = {'id', 'created_at', 'created_by', 'updated_at', 'updated_by', 'version', 'deleted', 'deleted_at'}
snake = lambda n: re.sub(r'(?<!^)(?=[A-Z])', '_', n).lower()
code = [f"using System.ComponentModel.DataAnnotations;\nusing HR.Common.Crud;\nusing HR.{svc}Service.Entities;\n\nnamespace HR.{svc}Service.DTOs;\n\n// <auto-generated> by scripts/generate-dtos.py from the existing MySQL schema - re-run after schema changes </auto-generated>\n"]
for spec in specs:
    parts = spec.split(':')
    ent, table = parts[0], parts[1]
    base = parts[2] if len(parts) > 2 and parts[2] else ent
    exclude = set(parts[3].split(',')) if len(parts) > 3 and parts[3] else set()
    src = open(f"src/Services/{svc}/HR.{svc}Service/Entities/{ent}.cs", encoding='utf-8-sig').read()
    props = re.findall(r'public ([\w?<>]+) (\w+) \{ get; set; \}', src)
    cols = {r[0]: r for r in q(f"select column_name,column_type,character_maximum_length,is_nullable,column_default,data_type from information_schema.columns where table_schema='{database}' and table_name='{table}'")}
    req, dto, defaults = [], [], []
    for typ, name in props:
        col = snake(name)
        if col not in cols: continue   # navigation or computed
        cname, ctype, clen, nullable, cdef, dtype = cols[col]
        dto_type = typ
        if name in exclude: continue   # excluded properties (e.g. encrypted columns) appear in neither request nor response
        if col != 'id' and col in SYS: 
            if col in ('created_at', 'updated_at'): dto.append(f"    public {typ} {name} {{ get; set; }}")
            continue
        dto.append(f"    public {dto_type} {name} {{ get; set; }}" + (" = \"\";" if dto_type == 'string' else ""))
        if col == 'id' or name in exclude: continue
        base_t = typ.rstrip('?')
        is_ref = base_t == 'string'
        has_def = cdef not in ('NULL', None, '') and not cdef.startswith('CURRENT_TIMESTAMP')
        required = nullable == 'NO' and not has_def and base_t != 'bool'
        if base_t == 'bool' and nullable == 'NO' and not has_def: has_def, cdef = True, ('1' if name in ('Active', 'Enabled') else '0')
        if ctype.startswith('enum') and nullable == 'NO' and not has_def and name in ('Status', 'Type'): has_def, cdef, required = True, re.findall(r"'([^']*)'", ctype)[0], False   # state-like enums default to their first value
        attrs = []
        if required: attrs.append('[Required]')
        if is_ref and clen not in ('NULL', None, ''):
            m = int(clen) if int(clen) < 100000 else 0
            if m: attrs.append(f'[StringLength({m})]')
        if ctype.startswith('enum'):
            vals = re.findall(r"'([^']*)'", ctype)
            attrs.append(f'[RegularExpression("^({"|".join(vals)})$")]')
        rtype = base_t if is_ref else base_t + '?'
        if is_ref: rtype += '?'
        req.append(f"    {' '.join(attrs)} public {rtype} {name} {{ get; set; }}")
        if has_def and not is_ref or (has_def and is_ref):
            lit = None
            d = cdef.strip("'")
            if base_t == 'bool': lit = 'true' if d in ('1', "b'1'", 'b\'1\'') or d.lower() == 'true' else 'false'
            elif base_t in ('int', 'long', 'short', 'decimal'): 
                try: float(d); lit = d + ('m' if base_t == 'decimal' else ('L' if base_t == 'long' else ''))
                except ValueError: lit = None
            elif base_t == 'string': lit = '"' + d.replace('"', '\\"') + '"'
            if lit is not None: defaults.append(f"        if ({name} is null) entity.{name} = {lit};")
    code.append(f"public sealed class {base}Request : IHasCreateDefaults<{ent}>\n{{\n" + "\n".join(req) + "\n\n    public void ApplyCreateDefaults(" + ent + " entity)\n    {\n" + "\n".join(defaults) + "\n    }\n}\n")
    code.append(f"public sealed class {base}Dto\n{{\n" + "\n".join(dto) + "\n}\n")
os.makedirs(os.path.dirname(out), exist_ok=True)
open(out, 'w').write("\n".join(code))
print(f"{svc}: {len(specs)} entities -> {out}")
