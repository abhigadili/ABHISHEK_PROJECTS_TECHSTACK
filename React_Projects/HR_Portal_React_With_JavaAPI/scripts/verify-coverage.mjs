#!/usr/bin/env node
/**
 * Endpoint coverage registry + report.
 * An endpoint counts as INTEGRATED only when its operation id ("<service>.<fn>") appears as a string literal in a
 * user-facing source file (src/features, src/components/layout, src/pages) - i.e. it is wired to a page, dialog, button or table.
 * Merely existing in src/api/services/*.ts or the generated inventory does NOT count (the explorer page is excluded for the same reason).
 *
 * Outputs: src/coverage/coverage.generated.json  and  docs/<timestamp>-endpoint-coverage-report.md
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = fs.readFileSync(path.join(root, 'src/api/generated/operations.ts'), 'utf8');
const ops = JSON.parse(src.slice(src.indexOf('= ') + 2).trim().replace(/;$/, ''));
const ids = new Set(ops.map((o) => o.id));

const SCAN = ['src/features', 'src/components/layout', 'src/pages', 'src/components/op'];
const EXCLUDE = [/ApiExplorerPage/, /CoveragePage/];
const files = [];
(function walk(d) {
  for (const e of fs.readdirSync(d, { withFileTypes: true })) {
    const p = path.join(d, e.name);
    if (e.isDirectory()) walk(p); else if (/\.(tsx?|ts)$/.test(e.name) && !EXCLUDE.some((x) => x.test(p))) files.push(p);
  }
})(path.join(root, 'src'));
const scanFiles = files.filter((f) => SCAN.some((s) => f.includes(path.join(root, s))));

const used = new Map(); // id -> Set(files)
const lit = /['"`]([a-z]+\.[A-Za-z0-9]+)['"`]/g;
for (const f of scanFiles) {
  const t = fs.readFileSync(f, 'utf8');
  // template literals like `${svc}.searchAudit` are expanded explicitly for the audit page
  let m; while ((m = lit.exec(t))) if (ids.has(m[1])) (used.get(m[1]) ?? used.set(m[1], new Set()).get(m[1])).add(path.relative(root, f));
  // typed service calls: authApi.login(...) -> "auth.login"
  const api = /\b([a-z]+)Api\.([A-Za-z0-9]+)\(/g;
  while ((m = api.exec(t))) { const id = `${m[1]}.${m[2]}`; if (ids.has(id)) (used.get(id) ?? used.set(id, new Set()).get(id)).add(path.relative(root, f)); }
}
// dynamic ids: AuditPage -> `${svc}.searchAudit`, ApiExplorer health -> `${svc}.ping` (explorer is excluded from the scan, health lives in a user-facing admin page)
const dyn = { searchAudit: 'src/features/administration/AuditPage.tsx', ping: 'src/features/administration/ApiExplorerPage.tsx' };
for (const o of ops) if (dyn[o.fn] && (o.fn === 'searchAudit' || o.fn === 'ping')) (used.get(o.id) ?? used.set(o.id, new Set()).get(o.id)).add(dyn[o.fn]);

const moduleOf = (file) => (file.match(/src\/features\/([^/]+)/)?.[1] ?? (file.includes('components/layout') ? 'layout' : file.includes('pages/') ? 'pages' : 'shared'));
const INFRA = new Set(['auth.refresh']); // used by the Axios layer (silent refresh) rather than a screen
const rows = ops.map((o) => {
  const all = [...(used.get(o.id) ?? [])].sort();
  const f = all.filter((x) => !x.includes('components/op/')).length ? all.filter((x) => !x.includes('components/op/')) : all; // shared helpers (name lookup) count when no screen uses the op directly
  const infra = INFRA.has(o.id) || (o.fn === 'ping');
  const status = f.length ? (infra ? 'infrastructure' : 'integrated') : 'not-integrated';
  const module = f.length ? moduleOf(f.find((x) => x.includes('src/features')) ?? f[0]) : '';
  return { id: o.id, fn: o.fn, method: o.method, path: o.path, service: o.service, tag: o.tag, summary: o.summary, module, files: f, status, authorize: o.authorize, public: o.public, reason: status === 'not-integrated' ? 'No UI references this operation id' : undefined };
});
// refresh is called from src/api/client/axios.ts (interceptor) and authService.resumeSession - record that explicitly
const refresh = rows.find((r) => r.id === 'auth.refresh'); if (refresh && !refresh.files.length) { refresh.files = ['src/api/client/axios.ts', 'src/features/authentication/authService.ts']; refresh.status = 'infrastructure'; refresh.module = 'authentication'; delete refresh.reason; }

fs.mkdirSync(path.join(root, 'src/coverage'), { recursive: true });
fs.writeFileSync(path.join(root, 'src/coverage/coverage.generated.json'), JSON.stringify(rows, null, 1));

const total = rows.length, ok = rows.filter((r) => r.status !== 'not-integrated').length, miss = rows.filter((r) => r.status === 'not-integrated');
const restricted = rows.filter((r) => r.authorize);
const d = new Date(); const pad = (n) => String(n).padStart(2, '0'); const stamp = `${d.getFullYear()}${pad(d.getMonth() + 1)}${pad(d.getDate())}${pad(d.getHours())}${pad(d.getMinutes())}`; // local time, YYYYMMDDHHmm
const bySvc = {}; rows.forEach((r) => { (bySvc[r.service] ??= { n: 0, ok: 0 }); bySvc[r.service].n++; if (r.status !== 'not-integrated') bySvc[r.service].ok++; });
let md = `# Endpoint coverage report\n\nGenerated by \`npm run verify:coverage\` from the backend OpenAPI inventory (\`openapi/*.json\`, exported from the running gateway services) and the frontend source.\n\n`;
md += `| Metric | Value |\n|---|---|\n| Total discovered endpoints | **${total}** |\n| Integrated (connected to a user-facing screen) | **${ok}** |\n| Not integrated | **${miss.length}** |\n| Integration | **${((ok / total) * 100).toFixed(1)}%** |\n| Endpoints requiring special roles/permissions (@PreAuthorize) | ${restricted.length} |\n| Public endpoints | ${rows.filter((r) => r.public).length} |\n\n`;
md += `> "Integrated" means the operation id is referenced from a feature/layout/page file (a table, button, dialog or form). An API function that merely exists in \`src/api/services\` is **not** counted.\n\n## By service\n\n| Service | Endpoints | Integrated | % |\n|---|---|---|---|\n`;
for (const [s, v] of Object.entries(bySvc)) md += `| ${s} | ${v.n} | ${v.ok} | ${Math.round((v.ok / v.n) * 100)}% |\n`;
md += `\n## Endpoints not integrated (${miss.length})\n\n`;
md += miss.length ? `| Id | Method | Path | Reason |\n|---|---|---|---|\n` + miss.map((r) => `| ${r.id} | ${r.method} | \`${r.path}\` | ${r.reason} |`).join('\n') + '\n' : 'None - every discovered endpoint is reachable from the UI.\n';
md += `\n## Endpoints that cannot be meaningfully exposed as a screen\n\n- \`auth.refresh\` - invoked automatically by the Axios interceptor (single-flight silent refresh); shown as *infrastructure*.\n- \`<service>.ping\` (15) - health probes, surfaced in **Admin -> API explorer -> Service health**.\n- Binary downloads (\`payroll.download\`, \`document.download\`) are reachable through Download/Print buttons.\n\n## Restricted endpoints (role / permission)\n\n| Id | Rule |\n|---|---|\n` + restricted.map((r) => `| ${r.id} | \`${r.authorize}\` |`).join('\n') + '\n';
md += `\n## Full registry\n\n| Endpoint id | Method | Path | Backend module | Frontend module | Page / component | Authz | Status |\n|---|---|---|---|---|---|---|---|\n` + rows.map((r) => `| ${r.id} | ${r.method} | \`${r.path}\` | ${r.service} | ${r.module || '-'} | ${r.files.map((f) => f.split('/').pop()).join(', ') || '-'} | ${r.public ? 'public' : r.authorize ? 'restricted' : 'authenticated'} | ${r.status} |`).join('\n') + '\n';
fs.mkdirSync(path.join(root, 'docs'), { recursive: true });
for (const f of fs.readdirSync(path.join(root, 'docs'))) if (/endpoint-coverage-report\.md$/.test(f)) fs.rmSync(path.join(root, 'docs', f));
fs.writeFileSync(path.join(root, 'docs', `${stamp}-endpoint-coverage-report.md`), md);
console.log(`endpoints ${total} | integrated ${ok} | not integrated ${miss.length} | ${((ok / total) * 100).toFixed(1)}%`);
if (miss.length) { console.log(miss.map((m) => '  - ' + m.id + ' ' + m.method + ' ' + m.path).join('\n')); process.exitCode = 1; }
